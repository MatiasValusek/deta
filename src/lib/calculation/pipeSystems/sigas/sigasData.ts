function accessoryRow(
  label: string,
  genericType: SigasAccessoryGenericType,
  equivalentLengthMeters: number,
  externalDiameterMeters: number,
  equivalentDiameterCount: number,
  sourcePage: number,
): SigasAccessoryEquivalentLengthRow {
  return {
    code: createAccessoryCode(label),
    equivalentDiameterCount,
    equivalentLengthMeters,
    externalDiameterMeters,
    genericType,
    label,
    sourcePage,
  };
}

function createAccessoryCode(label: string) {
  return label
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}
